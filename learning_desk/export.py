"""Markdown export for one session and JSON export of everything. No AI involved."""

import json

from . import db

KIND_LABELS = {"explanation": "Explanation", "application": "Application", "limitations": "Limitations / failure cases"}


def _section(title: str, body: str) -> str:
    return f"## {title}\n\n{body.strip() or '_(empty)_'}\n"


def _refs(refs: list[int]) -> str:
    return f" _(notes: {', '.join(f'S{r}' for r in refs)})_" if refs else ""


def session_markdown(session_id: int) -> str:
    s = db.get_session(session_id)
    if s is None:
        raise ValueError(f"Session {session_id} does not exist")
    out = [f"# {s['title'] or 'Untitled session'}\n"]
    if s["is_example"]:
        out.append("> Fictional example session created by Learning Desk.\n")
    out.append(f"- Topic: {s['topic'] or '-'}\n- Created: {s['created_at']}\n- Last saved: {s['updated_at']}\n")
    out.append(_section("What I want to understand", s["goal"]))
    out.append(_section("My current explanation", s["explanation"]))
    out.append(_section("Notes", s["notes"]))
    out.append(_section("Sources", s["sources"]))

    items = db.list_queue(session_id=session_id)
    lines = [f"- [{'x' if q['status'] == 'done' else ' '}] ({q['kind']}, {q['priority']}) {q['text']}"
             for q in items]
    out.append(_section("Questions and next steps", "\n".join(lines)))

    reviews = db.list_ai_calls(session_id, action="review", status="ok")
    if reviews:
        out.append("## AI reviews (generated by a model; not part of my notes)\n")
    for call in reviews:
        r = json.loads(call["parsed_json"])
        older = ", older format" if call["prompt_version"] == "review-v1" else ""
        out.append(f"### Review from {call['created_at']} (snapshot {call['snapshot_id']}, "
                   f"model {call['returned_model'] or call['requested_model']}, {call['prompt_version']}{older})\n")
        if call["prompt_version"] == "review-v1":
            out.extend(_review_v1_markdown(r))
        else:
            out.extend(_review_markdown(r))

    question_sets = db.list_question_sets(session_id)
    if question_sets:
        out.append("## Understanding questions\n")
    for qs in question_sets:
        if db.get_ai_call(qs['ai_call_id'])['action']=='quiz':
            out.append(quiz_markdown(qs['id']))
            continue
        out.append(f"### Questions from {qs['created_at']} (snapshot {qs['snapshot_id']})\n")
        for q in qs["questions"]:
            out.append(f"**{KIND_LABELS.get(q['kind'], q['kind'])}:** {q['text']}\n")
            out.append(f"Latest saved answer:\n\n{q['answer'].strip() or '_(not answered)_'}\n")
            for attempt in db.attempts(q['id']):
                out.append(f"Submitted attempt {attempt['id']} ({attempt['created_at']}, {attempt['provenance']}):\n\n{attempt['answer']}\n")
            for call in db.list_ai_calls(session_id, action="answer_feedback", status="ok", question_id=q["id"]):
                f = json.loads(call["parsed_json"])
                if call.get('attempt_id'):
                    attempt=db.query('SELECT * FROM answer_attempts WHERE id=?',(call['attempt_id'],))
                    evaluated=attempt[0]['answer'] if attempt else 'Historical evaluated answer unavailable'
                else:
                    evaluated='Historical evaluated answer could not be reconstructed from stored records.'
                out.append(f"Feedback from {call['created_at']} (generated by a model), evaluated answer:\n\n{evaluated}\n")
                out.append("- Explains well: " + ("; ".join(f["explains_well"]) or "-"))
                out.append("- Missing or possibly incorrect: " + (
                    "; ".join(f"{m['point']} ({m['why']})" for m in f["missing_or_possibly_incorrect"]) or "-"))
                out.append(f"- Follow-up exercise: {f['follow_up_exercise']}\n")
    out.append('## Original source snapshots for citations\n')
    for snapshot in db.query('SELECT * FROM snapshots WHERE session_id=? ORDER BY id',(session_id,)):
        out.append(f"### Snapshot {snapshot['id']}\n")
        content=json.loads(snapshot['content_json'])
        for section in content.get('sections',[]):
            out.append(f"S{section['id']} ({section['label']}):\n\n{section['text']}\n")
    out.append('## Linked learning resources\n')
    for link in db.query('SELECT resource_id FROM resource_sessions WHERE session_id=?',(session_id,)):
        out.append(resource_markdown(link['resource_id']))
    return "\n".join(out)


def _general_markdown(r: dict) -> list[str]:
    if not r["general_explanations"]:
        return []
    return ["**General explanations from the model (not from my notes)**\n\n" + "\n".join(
        f"- {g['topic']}: {g['explanation']}" for g in r["general_explanations"]) + "\n"]


def _review_markdown(r: dict) -> list[str]:
    out = [f"**Main takeaway:** {r['main_takeaway']['text']}{_refs(r['main_takeaway']['section_refs'])}\n"]
    if r["clarification"]:
        out.append(f"**One thing to clarify:** {r['clarification']['text']}"
                   f"{_refs(r['clarification']['section_refs'])}\n")
    out.append(f"**Next step ({r['next_step']['kind']}):** {r['next_step']['text']}\n")
    if r["supporting_evidence"]:
        out.append("**Supporting evidence from my notes**\n\n" + "\n".join(
            f"- {i['text']}{_refs(i['section_refs'])}" for i in r["supporting_evidence"]) + "\n")
    return out + _general_markdown(r)


def _review_v1_markdown(r: dict) -> list[str]:
    out = [f"{r['summary']}\n"]
    for key, title in (("observations", "Observations in my notes"),
                       ("interpretations", "My interpretations or assumptions"),
                       ("suggested_experiments", "Suggested experiments or questions")):
        if r[key]:
            out.append(f"**{title}**\n\n" + "\n".join(f"- {i['text']}{_refs(i['section_refs'])}" for i in r[key]) + "\n")
    if r["possible_gaps"]:
        out.append("**Possible gaps (hypotheses)**\n\n" + "\n".join(
            f"- {g['hypothesis']} How to check: {g['how_to_check']}{_refs(g['section_refs'])}"
            for g in r["possible_gaps"]) + "\n")
    out.extend(_general_markdown(r))
    if r["suggested_next_steps"]:
        out.append("**Suggested next steps**\n\n" + "\n".join(
            f"- ({n['kind']}) {n['text']}" for n in r["suggested_next_steps"]) + "\n")
    return out


def all_data_json() -> str:
    data = db.dump_all()
    return json.dumps({"app": "learning-desk", "exported_at": db.now(), **data}, indent=2, ensure_ascii=False)


def quiz_markdown(set_id):
    qs=db.query('SELECT * FROM question_sets WHERE id=?',(set_id,))[0]
    out=[f"## Quiz {set_id} (AI-generated)\n\nDifficulty: {qs['difficulty'] or 'not recorded'}; goal: {qs['practice_goal'] or 'not recorded'}; generation call: {qs['ai_call_id']}\n"]
    for q in db.query('SELECT * FROM questions WHERE set_id=? ORDER BY position',(set_id,)):
        out.append(f"### {q['text']}\n\nType: {q['question_type']}\n\nSaved AI key/rubric: {q['expected_answer']}\n\nSupporting references: {q['refs_json']}\n")
        for a in db.attempts(q['id']):
            out.append(f"Attempt {a['id']} ({a['created_at']}, {a['provenance']}):\n\n{a['answer']}\n")
            for f in db.query('SELECT * FROM attempt_feedback WHERE attempt_id=? ORDER BY id',(a['id'],)):
                out.append(f"Feedback {f['id']} for attempt {a['id']} (AI call {f['ai_call_id']}):\n\n{f['feedback_json']}\n")
        for report in db.query('SELECT * FROM issue_reports WHERE question_id=?',(q['id'],)):
            out.append(f"Issue report (attempt {report['attempt_id']}, feedback {report['feedback_id']}): {report['text']}\n")
    return '\n'.join(out)


def resource_markdown(resource_id):
    r=db.query('SELECT * FROM resources WHERE id=?',(resource_id,))[0]
    out=[f"# {r['title']}\n\n{r['resource_type']} Â· {r['level']} Â· {r['status']}\n\nSource: {r['url']}\n\nTags: {r['tags']}\n"]
    versions=db.query('SELECT * FROM content_versions WHERE resource_id=? ORDER BY id',(resource_id,))
    if not versions:
        out.append('Bookmark only; content not imported.\n')
    from .learning import source
    for v in versions:
        out.append(f"## Content version {v['id']} ({v['created_at']})\n\nSource: {v['source_url']}\n\n{v['import_note']}\n\n{v['text']}\n")
        out.append('### Source passage references\n')
        for passage in source(content_version_id=v['id']):
            out.append(f"S{passage['id']}:\n\n{passage['text']}\n")
        out.append('Extracted links (not read): '+v['links_json'])
        for summary in db.query('SELECT * FROM summaries WHERE content_version_id=? ORDER BY id',(v['id'],)):
            out.append(f"### {summary['kind']} (AI-generated, call {summary['ai_call_id']}, version {v['id']})\n\n{summary['result_json']}\n")
        for qs in db.query('SELECT id FROM question_sets WHERE content_version_id=?',(v['id'],)):
            out.append(quiz_markdown(qs['id']))
    links=db.query('SELECT session_id FROM resource_sessions WHERE resource_id=?',(resource_id,))
    out.append('Linked notebook session IDs: '+', '.join(str(r['session_id']) for r in links))
    return '\n'.join(out)
