# ---------------------------------------------------------------- calculations (pure, tested)

def softmax(logits, temperature=1.0):
    """Probabilities from scores. Temperature divides the scores first: below 1 sharpens,
    above 1 flattens. Temperature 0 is treated as 'always pick the highest score'."""
    if temperature <= 0:
        best = max(range(len(logits)), key=lambda i: logits[i])
        return [1.0 if i == best else 0.0 for i in range(len(logits))]
    scaled = [score / temperature for score in logits]
    top = max(scaled)
    weights = [math.exp(s - top) for s in scaled]
    total = sum(weights)
    return [w / total for w in weights]


def filter_top_k(probs, k):
    """Keep the k most likely options (ties broken by position) and renormalise."""
    if k <= 0 or k >= len(probs):
        return list(probs)
    keep = set(sorted(range(len(probs)), key=lambda i: (-probs[i], i))[:k])
    return _renormalise([p if i in keep else 0.0 for i, p in enumerate(probs)])


def filter_top_p(probs, p):
    """Nucleus filtering: keep the smallest set of most likely options whose total reaches p."""
    if p >= 1:
        return list(probs)
    order = sorted(range(len(probs)), key=lambda i: (-probs[i], i))
    keep, running = set(), 0.0
    for i in order:
        keep.add(i)
        running += probs[i]
        if running >= p - 1e-12:
            break
    return _renormalise([q if i in keep else 0.0 for i, q in enumerate(probs)])


def _renormalise(values):
    total = sum(values)
    return [v / total for v in values] if total else list(values)


def sampling_distribution(logits, temperature=1.0, top_k=0, top_p=1.0):
    """The order real samplers commonly use: temperature, then top-k, then top-p."""
    probs = softmax(logits, temperature)
    if top_k:
        probs = filter_top_k(probs, top_k)
    return filter_top_p(probs, top_p)


def pct(p):
    """A probability as a percentage, without rounding a small non-zero value to 0%."""
    if 0 < p < 0.005:
        return "under 1%"
    return f"{p:.0%}"


def cosine(a, b):
    dot = sum(x * y for x, y in zip(a, b))
    norm = math.sqrt(sum(x * x for x in a)) * math.sqrt(sum(y * y for y in b))
    if not norm:
        raise ValueError("Cosine similarity is undefined for a zero vector")
    return dot / norm


def rank_by_similarity(query, items):
    """items: {label: vector}. Returns [(label, similarity)] most similar first."""
    return sorted(((label, cosine(query, vec)) for label, vec in items.items()),
                  key=lambda pair: (-pair[1], pair[0]))


# Illustrative rates for the latency model. They are not measurements of any provider.
LATENCY_RATES = {"network_ms": 120, "prefill_base_ms": 200, "prefill_ms_per_1k_input": 40,
                 "ms_per_output_token": 15, "app_ms": 30}


def latency_breakdown(input_tokens, output_tokens, rates=LATENCY_RATES):
    """Where time goes in one non-streamed request, using simple illustrative rates."""
    return [
        ("Network and connection", rates["network_ms"]),
        ("Reading the input (prefill)",
         rates["prefill_base_ms"] + input_tokens / 1000 * rates["prefill_ms_per_1k_input"]),
        ("Generating output tokens", output_tokens * rates["ms_per_output_token"]),
        ("App validation and saving", rates["app_ms"]),
    ]


def time_to_first_token(input_tokens, rates=LATENCY_RATES):
    """With streaming, the first text can appear after network + prefill + one token."""
    return (rates["network_ms"] + rates["prefill_base_ms"]
            + input_tokens / 1000 * rates["prefill_ms_per_1k_input"] + rates["ms_per_output_token"])


def request_cost(input_tokens, output_tokens, input_price_per_mtok, output_price_per_mtok):
    return (input_tokens * input_price_per_mtok + output_tokens * output_price_per_mtok) / 1_000_000


