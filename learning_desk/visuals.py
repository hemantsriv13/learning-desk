def _t(x, y, s, size=14, anchor="middle", fill=TEXT, weight=400, family=FONT, italic=False):
    style = ' font-style="italic"' if italic else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}" fill="{fill}" '
            f'font-weight="{weight}" font-family="{family}"{style}>{escape(s)}</text>')


def _box(x, y, w, h, lines, tone="neutral", size=14, sub=None, dashed=False, radius=10):
    fill, stroke, colour = TONES[tone]
    dash = ' stroke-dasharray="5 4"' if dashed else ""
    out = [f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" '
           f'stroke="{stroke}" stroke-width="1.5"{dash}/>']
    lines = [lines] if isinstance(lines, str) else list(lines)
    total = len(lines) + (1 if sub else 0)
    gap = size + 5
    top = y + h / 2 - (total - 1) * gap / 2 + size * 0.35
    for i, line in enumerate(lines):
        out.append(_t(x + w / 2, top + i * gap, line, size, fill=colour, weight=600 if i == 0 else 400))
    if sub:
        out.append(_t(x + w / 2, top + len(lines) * gap, sub, size - 2, fill=MUTED))
    return "".join(out)


