def attention_weights():
    """One illustrative causal attention head: each row sums to 1 over itself and earlier tokens.
    Row 'it' is deliberately concentrated on 'animal'. These are not weights from a real model."""
    boosts = {(7, 1): 2.6, (7, 5): 1.0, (9, 1): 3.0, (9, 7): 2.5, (8, 7): 3.0, (5, 4): 2.0,
              (3, 1): 2.0, (2, 1): 2.0, (1, 0): 1.2, (6, 3): 1.5}
    rows = []
    for i in range(len(ATTENTION_TOKENS)):
        scores = [(1.0 + boosts.get((i, j), 0.0)) if j <= i else None for j in range(len(ATTENTION_TOKENS))]
        visible = [s for s in scores if s is not None]
        probs = iter(softmax(visible, 1.0))
        rows.append([next(probs) if s is not None else 0.0 for s in scores])
    return rows


