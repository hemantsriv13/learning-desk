def latency_timeline(input_tokens=3000, output_tokens=500, streaming=False):
    u = "lt"
    parts = latency_breakdown(input_tokens, output_tokens)
    total = sum(ms for _, ms in parts)
    scale = 600 / total
    tones = ["quiet", "accent", "warn", "ok"]
    body = [_t(24, 30, f"Illustrative timing for {input_tokens:,} input and {output_tokens:,} output tokens "
                       f"(rates are not measurements)", 13, "start", MUTED)]
    x = 24
    for (label, ms), tone in zip(parts, tones):
        w = ms * scale
        fill, stroke, colour = TONES[tone]
        body.append(f'<rect x="{x:.1f}" y="46" width="{max(w, 2):.1f}" height="44" fill="{fill}" stroke="{stroke}"/>')
        x += w
    y = 120
    for (label, ms), tone in zip(parts, tones):
        fill, stroke, colour = TONES[tone]
        body.append(f'<rect x="24" y="{y - 12}" width="14" height="14" fill="{fill}" stroke="{stroke}"/>')
        body.append(_t(46, y, f"{label}: {ms / 1000:.2f} s ({ms / total:.0%})", 13, "start", TEXT))
        y += 24
    body.append(_t(24, y + 6, f"Total until the full reply arrives: {total / 1000:.2f} s", 14, "start", TEXT, 600))
    if streaming:
        ttft = time_to_first_token(input_tokens)
        mx = 24 + ttft * scale
        body.append(f'<line x1="{mx:.1f}" y1="38" x2="{mx:.1f}" y2="98" stroke="{TONES["ok"][1]}" stroke-width="3"/>')
        body.append(_t(24, y + 30, f"Streaming: first words could appear after about {ttft / 1000:.2f} s "
                                    f"(green marker); the total is unchanged.", 13, "start", TONES["ok"][2]))
    height = y + (44 if streaming else 22)
    return _svg(u, 650, height, "Where time goes in a request",
                "A stacked bar of network, input processing, output generation and app time. "
                + "; ".join(f"{label} {ms / 1000:.2f} seconds" for label, ms in parts)
                + f". Total {total / 1000:.2f} seconds.", "".join(body))


